def load_reference_data(path):
    """Load unchanged legacy reference series from the explicitly named CSV."""
    series = {}
    with open(path, newline="", encoding="utf-8") as csv_file:
        reader = csv.DictReader(csv_file)
        if reader.fieldnames != ["series", "index", "value"]:
            raise ValueError(f"Unexpected reference-data CSV header: {path}")
        for row in reader:
            name = row["series"]
            index = int(row["index"])
            value = row["value"] if name == "queue_categories" else float(row["value"])
            series.setdefault(name, []).append((index, value))

    if not series:
        raise ValueError(f"Reference-data CSV is empty: {path}")

    data = {}
    for name, indexed_values in series.items():
        indexed_values.sort()
        indices = [index for index, _ in indexed_values]
        if indices != list(range(len(indices))):
            raise ValueError(f"Non-contiguous indices in series {name!r}: {path}")
        data[name] = np.asarray([value for _, value in indexed_values])
    return data


